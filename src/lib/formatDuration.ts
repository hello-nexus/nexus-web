/** ms → "1h 20m" / "45m" / "12s", cascading to the coarsest non-zero unit
 *  pair. Shared by Screen Time and the temperature chart's hover tooltip. */
export function formatDuration(ms: number): string {
  const totalSec = Math.floor(ms / 1000);
  const h = Math.floor(totalSec / 3600);
  const m = Math.floor((totalSec % 3600) / 60);
  const s = totalSec % 60;
  if (h > 0) return `${h}h ${m}m`;
  if (m > 0) return `${m}m`;
  return `${s}s`;
}
