#!/usr/bin/env node
/**
 * One-shot tool that converts a public-domain Natural Earth 110m land
 * GeoJSON into a precomputed, equirectangular-projected SVG path. The
 * output is committed at `src/panel/widgets/clock/worldMapData.ts` so
 * the runtime ships zero geo / projection / topojson dependencies — it
 * only imports the pre-baked path string and renders it.
 *
 * Re-run when you want to swap the projection, drop / raise the
 * coordinate precision, or refresh the source data:
 *
 *   1. download or update the source GeoJSON (Natural Earth, public
 *      domain) to `/tmp/land.geojson`:
 *      curl -sL https://d2ad6b4ur7yvpq.cloudfront.net/naturalearth-3.3.0/ne_110m_land.geojson \
 *        -o /tmp/land.geojson
 *   2. node scripts/build-world-map.mjs
 *   3. commit the resulting TS module.
 *
 * The projection is equirectangular: x = lon, y = -lat. ViewBox is
 * (-180,-90)–(180,90) — i.e. coordinates ARE lon/lat. Cities position
 * via the same trivial math at runtime; no projection helper needed.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const SRC = '/tmp/land.geojson';
const OUT = 'src/panel/widgets/clock/worldMapData.ts';

// "Simple shapes" target: ~10 KB of path data, recognisable continent
// silhouettes, no coastline minutiae. Achieved by aggressive vertex
// thinning + integer-degree precision + dropping micro-rings.
//
//   COORD_PRECISION 0    → integer-degree path coords (1° = ~111 km)
//   MIN_STEP_DEG    1.5  → skip vertices within 1.5° of the last kept
//   MIN_RING_SPAN_DEG 3  → drop a ring if its bounding box is smaller
//                          than 3° in both dimensions (= small islands)
const COORD_PRECISION = 0;
const MIN_STEP_DEG = 1.5;
const MIN_RING_SPAN_DEG = 3;

function projectAndRound(lon, lat) {
  return [
    Number(lon.toFixed(COORD_PRECISION)),
    Number((-lat).toFixed(COORD_PRECISION)), // SVG y grows downward
  ];
}

function ringBoundingSpan(ring) {
  let minLon = Infinity, maxLon = -Infinity;
  let minLat = Infinity, maxLat = -Infinity;
  for (const [lon, lat] of ring) {
    if (lon < minLon) minLon = lon;
    if (lon > maxLon) maxLon = lon;
    if (lat < minLat) minLat = lat;
    if (lat > maxLat) maxLat = lat;
  }
  return Math.min(maxLon - minLon, maxLat - minLat);
}

function thinRing(ring) {
  if (ring.length < 4) return [];
  const out = [];
  let last = null;
  for (const [lon, lat] of ring) {
    if (last === null
      || Math.abs(lon - last[0]) >= MIN_STEP_DEG
      || Math.abs(lat - last[1]) >= MIN_STEP_DEG) {
      out.push([lon, lat]);
      last = [lon, lat];
    }
  }
  // Close the ring back at its first vertex so the SVG polygon shuts
  // properly even if the last vertex got thinned away.
  if (out.length >= 3) out.push(out[0]);
  return out;
}

function ringToSubpath(ring) {
  if (ring.length === 0) return '';
  const parts = [];
  for (let i = 0; i < ring.length; i++) {
    const [lon, lat] = ring[i];
    const [x, y] = projectAndRound(lon, lat);
    parts.push(i === 0 ? `M${x},${y}` : `${x},${y}`);
  }
  return parts.join('L').replace(/^M(.*?)L/, 'M$1L') + 'Z';
}

function polygonsFromGeometry(geom) {
  if (geom.type === 'Polygon') return [geom.coordinates];
  if (geom.type === 'MultiPolygon') return geom.coordinates;
  return [];
}

const geojson = JSON.parse(readFileSync(SRC, 'utf8'));
if (geojson.type !== 'FeatureCollection') {
  console.error('Expected a FeatureCollection in', SRC);
  process.exit(1);
}

const subpaths = [];
let droppedSmall = 0;
let droppedThin = 0;
for (const feature of geojson.features) {
  const polygons = polygonsFromGeometry(feature.geometry);
  for (const polygon of polygons) {
    for (const ring of polygon) {
      if (ringBoundingSpan(ring) < MIN_RING_SPAN_DEG) { droppedSmall += 1; continue; }
      const thinned = thinRing(ring);
      if (thinned.length < 4) { droppedThin += 1; continue; }
      const sp = ringToSubpath(thinned);
      if (sp) subpaths.push(sp);
    }
  }
}

const path = subpaths.join('');

const out = `// Generated by scripts/build-world-map.mjs — do not edit by hand.
// Pre-projected (equirectangular) Natural Earth 110m land coastline.
// Public domain. ViewBox is -180,-90,360,180 so lon/lat map directly:
//   x = lon (degrees east)
//   y = -lat (SVG y is south-positive)
// Cities position via the same identity projection at runtime.

export const WORLD_MAP_VIEWBOX = '-180 -90 360 180' as const;
export const WORLD_MAP_PATH = ${JSON.stringify(path)};
`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}`);
console.log(`  subpaths kept:   ${subpaths.length}`);
console.log(`  dropped small:   ${droppedSmall}`);
console.log(`  dropped thinned: ${droppedThin}`);
console.log(`  path length:     ${(path.length / 1024).toFixed(1)} KB`);
