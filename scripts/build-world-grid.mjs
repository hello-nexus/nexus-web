#!/usr/bin/env node
/**
 * Rasterises the public-domain Natural Earth 110m land GeoJSON into a
 * coarse land/ocean bit grid, committed at
 * `src/panel/widgets/clock/worldGridData.ts`. The world-clock map renders
 * the grid as a field of small squares (one <rect> per land cell) instead
 * of a coastline path - the pixelated look - while staying in the same
 * equirectangular lon/lat space as the city pins and terminator.
 *
 * A cell is land when its centre point falls inside a land outer ring and
 * outside every hole (lake) of that polygon.
 *
 * Re-run when swapping the source data or changing CELL_DEG:
 *   1. curl -sL https://d2ad6b4ur7yvpq.cloudfront.net/naturalearth-3.3.0/ne_110m_land.geojson -o /tmp/land.geojson
 *   2. node scripts/build-world-grid.mjs
 *   3. commit the resulting TS module.
 */

import { readFileSync, writeFileSync } from 'node:fs';

const SRC = '/tmp/land.geojson';
const OUT = 'src/panel/widgets/clock/worldGridData.ts';

// Cell size in degrees: chunky pixels that still read as recognisable
// continents. Smaller = finer pixels and more <rect> nodes.
const CELL_DEG = 2;

const COLS = Math.round(360 / CELL_DEG);
const ROWS = Math.round(180 / CELL_DEG);

function polygonsFromGeometry(geom) {
  if (geom.type === 'Polygon') return [geom.coordinates];
  if (geom.type === 'MultiPolygon') return geom.coordinates;
  return [];
}

// Ray-cast point-in-ring. ring is [[lon,lat],...]; returns true if (x,y) is
// inside.
function pointInRing(x, y, ring) {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const xi = ring[i][0], yi = ring[i][1];
    const xj = ring[j][0], yj = ring[j][1];
    const intersects = (yi > y) !== (yj > y)
      && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi;
    if (intersects) inside = !inside;
  }
  return inside;
}

// A polygon is [outerRing, ...holeRings]. Inside = in outer, not in any hole.
function pointInPolygon(x, y, polygon) {
  if (!pointInRing(x, y, polygon[0])) return false;
  for (let h = 1; h < polygon.length; h++) {
    if (pointInRing(x, y, polygon[h])) return false;
  }
  return true;
}

const geojson = JSON.parse(readFileSync(SRC, 'utf8'));
if (geojson.type !== 'FeatureCollection') {
  console.error('Expected a FeatureCollection in', SRC);
  process.exit(1);
}

const polygons = [];
for (const feature of geojson.features) {
  for (const polygon of polygonsFromGeometry(feature.geometry)) polygons.push(polygon);
}

// Cheap per-polygon bounding boxes so each cell only tests polygons it could
// fall in (the rasterise is otherwise cells × polygons × vertices).
const bounds = polygons.map(poly => {
  let minX = Infinity, minY = Infinity, maxX = -Infinity, maxY = -Infinity;
  for (const [x, y] of poly[0]) {
    if (x < minX) minX = x; if (x > maxX) maxX = x;
    if (y < minY) minY = y; if (y > maxY) maxY = y;
  }
  return { minX, minY, maxX, maxY };
});

let landCount = 0;
const rows = [];
for (let r = 0; r < ROWS; r++) {
  const lat = 90 - (r + 0.5) * CELL_DEG;
  let line = '';
  for (let c = 0; c < COLS; c++) {
    const lon = -180 + (c + 0.5) * CELL_DEG;
    let land = false;
    for (let p = 0; p < polygons.length; p++) {
      const b = bounds[p];
      if (lon < b.minX || lon > b.maxX || lat < b.minY || lat > b.maxY) continue;
      if (pointInPolygon(lon, lat, polygons[p])) { land = true; break; }
    }
    line += land ? '1' : '0';
    if (land) landCount += 1;
  }
  rows.push(line);
}

const out = `// Generated by scripts/build-world-grid.mjs - do not edit by hand.
// Natural Earth 110m land rasterised to a ${COLS}×${ROWS} land/ocean grid
// (public domain). The clock world map draws one square per land cell in the
// same equirectangular space as the city pins:
//   lon = -180 + (col + 0.5) * CELL_DEG
//   lat =   90 - (row + 0.5) * CELL_DEG   (row 0 = north)
// Each \`land\` string is one row north→south; '1' = land, '0' = ocean.

export const WORLD_GRID = {
  cellDeg: ${CELL_DEG},
  cols: ${COLS},
  rows: ${ROWS},
  land: [
${rows.map(line => `    '${line}',`).join('\n')}
  ],
} as const;
`;

writeFileSync(OUT, out);
console.log(`wrote ${OUT}`);
console.log(`  grid:       ${COLS}×${ROWS} (${CELL_DEG}°)`);
console.log(`  land cells: ${landCount}`);
console.log(`  size:       ${(out.length / 1024).toFixed(1)} KB`);
